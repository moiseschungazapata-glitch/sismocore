import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const browser = await chromium.launch({ channel:'chrome',headless:true });
const origin = 'http://localhost:5173';
const event = { id:'map-test', id_externo:'2026-747', magnitud:4, tipo_magnitud:null, lugar:'Andoas, Loreto', profundidad:141, latitud:-2.68, longitud:-77.23, ocurrido_en:new Date().toISOString(), estado_revision:'reportado_igp', url_fuente:'https://ide.igp.gob.pe/' };
const errors = [];
const issues = [];
try {
  const page = await browser.newPage({ viewport:{ width:1440,height:1000 } });
  page.setDefaultTimeout(25000);
  const waitForTiles = () => page.waitForFunction(() => {
    const images = [...document.querySelectorAll('.leaflet-tile')];
    return images.length > 0 && images.every(image => image.complete && image.naturalWidth > 0);
  });
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/api/v1/auth/me', route => route.fulfill({ json:{ user:{ id:'map-user',nombre_completo:'Prueba',email:'test@example.org',rol:'lectura',estado:'activo',permisos:['catalogo.leer'] } } }));
  await page.route('**/health', route => route.fulfill({ json:{ estado:'saludable',base_datos:'conectada',configurada:true } }));
  await page.route('**/api/v1/eventos', route => route.fulfill({ json:{ total:1,eventos:[event],codigo_fuente:'igp',fuente:'IGP',periodo_dias:30,frecuencia_segundos:600,consultado_en:new Date().toISOString(),ultima_sincronizacion:new Date().toISOString(),ultima_ejecucion:null } }));
  await page.goto(origin + '/mapa?q=Andoas');
  const toggle = page.getByRole('button', { name:'Cambiar a vista satelital',exact:true });
  await toggle.waitFor();
  const zoom = page.getByRole('button', { name:'Zoom in',exact:true });
  await zoom.click();
  const bounds = await page.locator('.leaflet-interactive').first().getAttribute('d');
  const transform = await page.locator('.leaflet-map-pane').getAttribute('style');
  await toggle.click();
  await page.waitForFunction(() => [...document.querySelectorAll('.leaflet-tile-loaded')].some(tile => tile.src.includes('BlueMarble')));
  await waitForTiles();
  assert.equal(await page.locator('.leaflet-interactive').count(),1);
  assert.equal(await page.locator('.leaflet-interactive').first().getAttribute('d'),bounds);
  assert.equal(await page.locator('.leaflet-map-pane').getAttribute('style'),transform);
  assert.ok(page.url().includes('q=Andoas'));
  assert.ok(await page.locator('.leaflet-control-attribution').innerText().then(text => text.includes('NASA')));
  await mkdir('.runtime/map-style',{ recursive:true });
  await page.screenshot({ path:'.runtime/map-style/satelite-desktop.png',fullPage:true });
  async function axe(label) {
    if (!process.env.AXE_SCRIPT) return;
    await page.addScriptTag({ path:process.env.AXE_SCRIPT });
    const result = await page.evaluate(async () => (await window.axe.run(document,{ runOnly:{ type:'tag',values:['wcag2a','wcag2aa','wcag21a','wcag21aa','best-practice'] } })).violations.map(v => ({ id:v.id,nodes:v.nodes.map(n => ({ target:n.target,summary:n.failureSummary })) })));
    if (result.length) issues.push({ label,result });
  }
  await axe('satélite escritorio');
  await page.reload();
  await page.getByRole('button', { name:'Cambiar a vista de mapa',exact:true }).waitFor();
  assert.equal(await page.evaluate(() => localStorage.getItem('sismocore.map-style.v1')),'satelite');
  await page.setViewportSize({ width:390,height:900 });
  await page.waitForTimeout(200);
  await waitForTiles();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false);
  await page.screenshot({ path:'.runtime/map-style/satelite-mobile.png',fullPage:true });
  await axe('satélite móvil');
  const back = page.getByRole('button', { name:'Cambiar a vista de mapa',exact:true });
  await back.focus();
  await page.keyboard.press('Enter');
  await toggle.waitFor();
  assert.equal(await page.locator('.leaflet-tile-container img').evaluateAll(images => images.some(image => image.src.includes('BlueMarble'))),false);
  await page.setViewportSize({ width:320,height:900 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false);
  await page.route('**/gibs.earthdata.nasa.gov/**', route => route.abort());
  await page.reload({ waitUntil:'domcontentloaded' });
  await toggle.waitFor();
  await toggle.click();
  await page.getByRole('alert').filter({ hasText:'No se pudieron cargar algunas imágenes' }).waitFor();
  await page.getByRole('button', { name:'Cambiar a vista de mapa',exact:true }).click();
  assert.equal(await page.getByRole('alert').count(),0);
  assert.deepEqual(errors,[]);
  assert.deepEqual(issues,[]);
  console.log('Mapa/satélite: teselas NASA reales, zoom y filtros conservados, preferencia al recargar, teclado, móvil y recuperación ante error correctos.');
} finally { await browser.close(); }
